def capture(destination):
    """Ask the real desktop compositor for a screenshot; user consent may be required."""
    if destination.exists():
        raise RuntimeError('Refusing to overwrite existing screenshot: ' + str(destination))
    import gi
    gi.require_version('Gio', '2.0')
    from gi.repository import Gio, GLib
    connection=Gio.bus_get_sync(Gio.BusType.SESSION, None)
    loop=GLib.MainLoop()
    response={}
    token='jenkins_' + str(time.time_ns())
    def on_response(conn, sender, object_path, interface, signal, parameters, userdata):
        if object_path.endswith('/' + token):
            response['value']=parameters.unpack()
            loop.quit()
    subscription=connection.signal_subscribe(None, 'org.freedesktop.portal.Request', 'Response',
        None, None, Gio.DBusSignalFlags.NONE, on_response, None)
    options={'handle_token':GLib.Variant('s',token),'interactive':GLib.Variant('b',False)}
    connection.call_sync('org.freedesktop.portal.Desktop','/org/freedesktop/portal/desktop',
        'org.freedesktop.portal.Screenshot','Screenshot',GLib.Variant('(sa{sv})',('',options)),
        None,Gio.DBusCallFlags.NONE,10000,None)
    timeout=GLib.timeout_add_seconds(180, lambda: (loop.quit(), False)[1])
    loop.run()
    connection.signal_unsubscribe(subscription)
    if 'value' not in response: raise RuntimeError('Screenshot portal did not respond')
    code, results=response['value']
    if code != 0: raise RuntimeError('Screenshot portal rejected/cancelled capture: '+str(code))
    uri=results['uri']
    if not uri.startswith('file:'):raise RuntimeError('Unexpected screenshot URI scheme')
    source=pathlib.Path(urllib.parse.unquote(urllib.parse.urlparse(uri).path))
    shutil.copyfile(source,destination)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--capture',action='store_true',help='Use native screenshot portal; may require local Share clicks')
    parser.add_argument('--page',type=int,choices=range(1,10),help='Display just one numbered page')
    args=parser.parse_args()
    state={'started':datetime.datetime.now().astimezone().isoformat(),'captures':[]}
    pages=[args.page-1] if args.page else range(len(PAGES))
    for number in pages:
        name=page(number,state)
        if args.capture:
            print('Ubuntu screenshot portal: approve Share locally if prompted.',flush=True)
            time.sleep(1)
            try:
                capture(ROOT/'evidence/screenshots'/name)
            except Exception as error:
                print('NATIVE CAPTURE BLOCKER: '+str(error),flush=True)
                print('Use Ubuntu Print Screen manually and save as evidence/screenshots/'+name,flush=True)
                input('Terminal is ready. Press Enter only after saving this screenshot: ')
        else:
            print('Save a real screenshot as evidence/screenshots/'+name,flush=True)
            input('Use Ubuntu Print Screen; press Enter only after saving this screenshot: ')
        state['captures'].append({'file':'evidence/screenshots/'+name,'page':number+1,
                                 'exists':(ROOT/'evidence/screenshots'/name).exists()})
        (ROOT/'.lab/terminal-capture-session.json').write_text(json.dumps(state,indent=2)+'\n')
    print('Terminal views complete. Screenshots still need inspection before publication.',flush=True)
    input('Press Enter to close this terminal: ')

if __name__=='__main__':
    main()
